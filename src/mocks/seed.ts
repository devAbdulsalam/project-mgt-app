type Partialish = Partial<Ticket> & Pick<Ticket, 'key' | 'title'>;

function t(input: Partialish): Ticket {
	const projectKey = input.projectKey ?? input.key.split('-')[0]!;
	const createdAt = input.createdAt ?? hr(4);
	return {
		projectKey,
		category: '',
		type: projectKey === 'KS' || projectKey === 'NET' ? 'support' : 'task',
		priority: 'P3',
		status: 'Open',
		channel: projectKey === 'KS' ? 'email' : 'internal',
		reporter: { name: 'Adaeze Okonkwo', isClient: false, id: 'u_adaeze' },
		labels: [],
		description: '',
		createdAt,
		updatedAt: input.updatedAt ?? createdAt,
		timeLoggedMin: 0,
		subtasks: [],
		links: [],
		comments: [],
		activity: [{ id: `${input.key}-a0`, at: createdAt, actorName: input.reporter?.name ?? 'Adaeze Okonkwo', text: 'created the ticket', system: false }],
		attachments: [],
		watcherIds: [],
		mentionedIds: [],
		createdById: input.reporter?.id ?? 'u_adaeze',
		...input,
	};
}

